// Generates the provider's secrets for local development and appends them to an env
// file (default: .env), without printing them. Refuses to overwrite existing keys:
// rotating means adding a key to OIDC_JWKS, not replacing it (see the README).
//
// Usage: nx run identity:generate-keys   (or: node scripts/generate-keys.mjs [file])
import { generateKeyPairSync, randomBytes, randomUUID } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync } from 'node:fs';

const file = process.argv[2] ?? '.env';
const existing = existsSync(file) ? readFileSync(file, 'utf8') : '';
if (/^OIDC_(JWKS|COOKIE_KEYS)=/m.test(existing)) {
  console.error(`${file} already has OIDC keys; nothing changed.`);
  process.exit(1);
}

const { privateKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
const jwk = {
  ...privateKey.export({ format: 'jwk' }),
  kid: randomUUID(),
  alg: 'ES256',
  use: 'sig',
};
const cookieKey = randomBytes(32).toString('base64url');

// Single quotes: dotenv takes the JSON literally, without variable expansion
appendFileSync(
  file,
  [
    '',
    '# Generated by scripts/generate-keys.mjs. Secrets: never commit them.',
    `OIDC_JWKS='${JSON.stringify({ keys: [jwk] })}'`,
    `OIDC_COOKIE_KEYS=${cookieKey}`,
    '',
  ].join('\n'),
);
console.log(
  `Added OIDC_JWKS (kid ${jwk.kid}) and OIDC_COOKIE_KEYS to ${file}.`,
);
